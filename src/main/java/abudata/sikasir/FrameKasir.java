    private void HitungTotal() {
        try {
            int jumlah = Integer.parseInt(InputJumlah.getText());
            int harga = Integer.parseInt(InputHarga.getText());
            String nama = InputNB.getText();
            
            if(harga <= 0 || jumlah <= 0){
                JOptionPane.showMessageDialog(this,"harga dan jumlah nguwawor");
                return;
            } else if (nama.length() <= 0 ) {
                JOptionPane.showMessageDialog(this,"nama barang isi woy");
                return;
            }
            
            int total = (harga * jumlah);
            InputTotal.setText(Integer.toString(total));
        } 
        catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,"Harga dan jumlah harus berupa angka!");
        } 
    }
    
    private void Bayar(){
        int bayar = Integer.parseInt(InputUB.getText());
        int harga = Integer.parseInt(InputHarga.getText());
        int jumlah = Integer.parseInt(InputJumlah.getText());
        int total = harga * jumlah;
        int kembalian = bayar - total;
        InputUK.setText(Integer.toString(kembalian));  
    }
