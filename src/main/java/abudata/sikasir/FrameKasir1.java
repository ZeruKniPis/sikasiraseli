    private void HitungTotal() {
        try {
            int jumlah = Integer.parseInt(InputJumlah.getText());
            double harga = Double.parseDouble(InputHarga.getText());
            String nama = InputNB.getText();
            
            if(harga <= 0 || jumlah <= 0){
                JOptionPane.showMessageDialog(this,"harga dan jumlah kurang");
                return;
            } else if (nama.length() <= 0 ) {
                JOptionPane.showMessageDialog(this,"nama barang isi woy");
                return;
            }
            
            if(nama.isEmpty()){
                JOptionPane.showMessageDialog(this,"barangnya apa?");        
            }
            
            Barang barang = new Barang(nama,harga);
            //transaksi.resetTransaksi();
            transaksi.tambahBarang( barang, jumlah);
            
            int total = (int) (transaksi.hitungTotal());
            InputTotal.setText(String.valueOf(total));
        } 
        catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,"Harga dan jumlah harus berupa angka!");
        } 
    }
    
    private void Bayar(){
        int bayar = Integer.parseInt(InputUB.getText());
        Double harga = Double.valueOf(InputHarga.getText());
        int jumlah = Integer.parseInt(InputJumlah.getText());
        Double total = harga * jumlah;
        Double kembalian = bayar - total;
        InputUK.setText(Double.toString(kembalian));  
    }
